/** The character of screen code `n` (0..63). */
export const screenChar = (n) => (n < 32 ? '@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_'[n] : String.fromCharCode(n));

/** Glyph `n` (screen code 0..63) as 8 rows of 8 '.'/'1' pixels. */
export function glyph(n) {
  const g = GLYPHS[screenChar(n)];
  const rows = [];
  for (let y = 0; y < 8; y++) {
    let bits = 0;
    const src = y < 7 ? g[y] : '.....';
    for (let x = 0; x < 5; x++) if (src[x] === '#') bits |= 0x40 >> x; // columns 1..5
    rows.push([...Array(8)].map((_, i) => (bits & (0x80 >> i) ? '1' : '.')).join(''));
  }
  return rows;
}

/** The 64 font tiles, ready for tiles.json. */
export function fontTiles() {
  return [...Array(64)].map((_, n) => ({ name: n === 32 ? 'space' : `font ${screenChar(n)}`, multi: false, color: 1, flags: 0, rows: glyph(n) }));
}
